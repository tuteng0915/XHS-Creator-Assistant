import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { CreatorNoteSelectionDialog } from './CreatorNoteSelectionDialog'
import type { CreatorNote } from '../creatorNotes'

afterEach(cleanup)
const notes: CreatorNote[] = Array.from({length:12}, (_, i) => ({
  noteId: `n${i}`, title: `笔记 ${i}`, desc: `正文 ${i}`, metrics: {liked: i}, comments: [{content: `评论 ${i}`}],
}))

it('reuses note cards and details and commits only an explicit selection', () => {
  const confirm = vi.fn()
  render(<CreatorNoteSelectionDialog notes={notes} mediaAssets={[]} scope="recent_10" onConfirm={confirm} onClose={vi.fn()} />)
  expect(screen.getAllByRole('checkbox').filter(el => (el as HTMLInputElement).checked)).toHaveLength(10)
  fireEvent.click(screen.getByRole('button', {name: '取消选择'}))
  expect(screen.getByRole('button', {name: '完成'})).toBeDisabled()
  fireEvent.click(screen.getByRole('checkbox', {name: '选择笔记：笔记 11'}))
  expect(screen.getByRole('status')).toHaveTextContent('已选 1 / 12')
  fireEvent.click(screen.getByRole('button', {name: /笔记 11 赞/}))
  const detail = screen.getByRole('dialog', {name:'笔记 11'})
  expect(within(detail).getByText('正文 11')).toBeInTheDocument()
  expect(within(detail).getByText('评论 11')).toBeInTheDocument()
  fireEvent.click(within(detail).getByRole('button', {name:'关闭'}))
  expect(confirm).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', {name:'完成'}))
  expect(confirm).toHaveBeenCalledWith('recent_10', ['n11'])
})

it('cancels without applying and explicitly confirms exact IDs for quick selections', () => {
  const confirm = vi.fn(), close = vi.fn()
  render(<CreatorNoteSelectionDialog notes={notes} mediaAssets={[]} scope="recent_10" selectedIds={['n11']} onConfirm={confirm} onClose={close} />)
  fireEvent.click(screen.getByRole('button', {name:'全选当前范围'}))
  expect(screen.getByRole('status')).toHaveTextContent('已选 12 / 12')
  fireEvent.click(screen.getByRole('button', {name:'取消'}))
  expect(close).toHaveBeenCalledOnce()
  expect(confirm).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', {name:'选前 10 篇'}))
  fireEvent.click(screen.getByRole('button', {name:'完成'}))
  expect(confirm).toHaveBeenCalledWith('recent_10', ['n0','n1','n10','n11','n2','n3','n4','n5','n6','n7'])
})

it('ranks likes and interaction with custom N and allows manual adjustment', () => {
  const confirm = vi.fn()
  render(<CreatorNoteSelectionDialog notes={notes} mediaAssets={[]} scope="all" onConfirm={confirm} onClose={vi.fn()} />)
  fireEvent.change(screen.getByLabelText('排序'), {target:{value:'liked'}})
  expect(screen.getByRole('status')).toHaveTextContent('已选 12 / 12')
  fireEvent.change(screen.getByLabelText('数量'), {target:{value:'custom'}})
  fireEvent.change(screen.getByLabelText('自定义篇数'), {target:{value:'2'}})
  fireEvent.click(screen.getByRole('button',{name:'选前 2 篇'}))
  expect(screen.getByRole('status')).toHaveTextContent('已选 2 / 12')
  expect(screen.getByRole('checkbox',{name:'选择笔记：笔记 11'})).toBeChecked()
  expect(screen.getByRole('checkbox',{name:'选择笔记：笔记 10'})).toBeChecked()
  fireEvent.click(screen.getByRole('checkbox',{name:'选择笔记：笔记 0'}))
  fireEvent.click(screen.getByRole('button',{name:'完成'}))
  expect(confirm).toHaveBeenCalledWith('most_liked_10',['n11','n10','n0'])
})

it('filters without deleting outside selections and inverts the entire current range', () => {
  const recent = new Date().toISOString()
  const sample = [...notes.slice(0,3).map(note => ({...note,publishedAt:recent})), {...notes[3],publishedAt:'2020-01-01'}]
  const confirm = vi.fn()
  render(<CreatorNoteSelectionDialog notes={sample} mediaAssets={[]} scope="all" selectedIds={['n0','n3']} onConfirm={confirm} onClose={vi.fn()} />)
  fireEvent.change(screen.getByLabelText('查看范围'),{target:{value:'last_7_days'}})
  expect(screen.getAllByRole('checkbox')).toHaveLength(3)
  expect(screen.getByRole('status')).toHaveTextContent('已选 2 / 4')
  expect(screen.getByRole('status')).toHaveTextContent('1 篇不在当前范围')
  fireEvent.click(screen.getByRole('button',{name:'反选当前范围'}))
  expect(screen.getByRole('status')).toHaveTextContent('已选 3 / 4')
  expect(screen.getByRole('checkbox',{name:'选择笔记：笔记 0'})).not.toBeChecked()
  fireEvent.click(screen.getByRole('button',{name:'完成'}))
  expect(confirm).toHaveBeenCalledWith('last_7_days',['n3','n1','n2'])
})

it('single mode preserves sorting and preview but never allows multiple selection', () => {
  const confirm = vi.fn()
  render(<CreatorNoteSelectionDialog notes={notes} mediaAssets={[]} scope="all" selectedIds={['n0']} onConfirm={confirm} onClose={vi.fn()} selectionMode="single" title="选择试读笔记" />)
  expect(screen.getByRole('dialog',{name:'选择试读笔记'})).toBeVisible()
  expect(screen.queryByRole('button',{name:/全选|反选|选前/})).not.toBeInTheDocument()
  expect(screen.getByRole('status')).not.toHaveTextContent('包含对应评论')
  fireEvent.change(screen.getByLabelText('排序'),{target:{value:'engagement'}})
  fireEvent.click(screen.getByRole('radio',{name:'选择笔记：笔记 11'}))
  expect(screen.getAllByRole('radio').filter(el => (el as HTMLInputElement).checked)).toHaveLength(1)
  fireEvent.click(screen.getByRole('button',{name:'完成'}))
  expect(confirm).toHaveBeenCalledWith('most_engaged_10',['n11'])
})

it('does not choose unknown metrics automatically or accept non-positive custom counts', () => {
  render(<CreatorNoteSelectionDialog notes={[{...notes[0],metrics:{}}]} mediaAssets={[]} scope="all" onConfirm={vi.fn()} onClose={vi.fn()} />)
  fireEvent.change(screen.getByLabelText('排序'),{target:{value:'engagement'}})
  fireEvent.click(screen.getByRole('button',{name:'选前 10 篇'}))
  expect(screen.getByRole('button',{name:'完成'})).toBeDisabled()
  expect(screen.getByRole('checkbox')).toBeVisible()
  fireEvent.change(screen.getByLabelText('数量'), {target:{value:'custom'}})
  fireEvent.change(screen.getByLabelText('自定义篇数'), {target:{value:'0'}})
  expect(screen.getByRole('button',{name:'选前 N 篇'})).toBeDisabled()
})

it('keeps an explicitly empty selection and requires reducing an over-limit set instead of truncating it', () => {
  const confirm = vi.fn()
  render(<CreatorNoteSelectionDialog notes={notes} mediaAssets={[]} scope="all" selectedIds={[]} maxSelection={2} includeComments={false} onConfirm={confirm} onClose={vi.fn()} />)
  expect(screen.getByRole('status')).toHaveTextContent('已选 0 / 12')
  expect(screen.getByRole('status')).not.toHaveTextContent('包含对应评论')
  expect(screen.getByRole('button', {name: '完成'})).toBeDisabled()
  fireEvent.click(screen.getByRole('button', {name: '全选当前范围'}))
  expect(screen.getByRole('status')).toHaveTextContent('已选 12 / 12')
  expect(screen.getByRole('alert')).toHaveTextContent('本次最多还能添加 2 篇原笔记，请减少选择后再完成。')
  expect(screen.getByRole('button', {name: '完成'})).toBeDisabled()
  expect(confirm).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', {name: '取消选择'}))
  fireEvent.click(screen.getByRole('checkbox', {name: '选择笔记：笔记 1'}))
  fireEvent.click(screen.getByRole('checkbox', {name: '选择笔记：笔记 2'}))
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  fireEvent.click(screen.getByRole('button', {name: '完成'}))
  expect(confirm).toHaveBeenCalledExactlyOnceWith('all', ['n1', 'n2'])
})
